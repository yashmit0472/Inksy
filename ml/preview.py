"""Inference-only text-to-handwriting page preview with PNG exports and an HTML comparison."""

import argparse
import time
from dataclasses import asdict
from pathlib import Path

import torch
from PIL import Image
from tqdm import tqdm

from ml.characters import CHAR_TO_LABEL, normalize_text, validate_text
from ml.checkpoint import load_checkpoint
from ml.utils import resolve_device, seed_everything, sha256_file, write_json
from rendering.compositor import RENDERER_VERSION, LayoutOptions, compose_pages, layout_text
from rendering.report import write_report

DEFAULT_CHECKPOINT = Path("artifacts/refined-continue-5/best.pt")
DEMO_TEXT = (
    "Hello, this is Inksy.\n\n"
    "This page is generated by our own handwriting model. "
    "Each letter and digit is sampled from the trained decoder.\n\n"
    "The quick brown fox jumps over the lazy dog.\n"
    "Numbers: 0123456789. Mixed case: Aa Bb Cc Dd.\n\n"
    "Some letters may be unclear or incorrect. "
    "This preview helps us inspect words, spacing, and line breaks."
)


def prepare_text(text: str, apply_normalization=False) -> str:
    if len(text) > 12_000:
        raise ValueError("Raw input exceeds the 12,000-character safety limit.")
    rendered = normalize_text(text) if apply_normalization else text
    validate_text(rendered)
    return rendered


@torch.inference_mode()
def sample_occurrences(model, text: str, seed: int, *, batch_size=128, show_progress=True):
    validate_text(text)
    if not 0 <= seed < 2**63:
        raise ValueError("Seed must be an integer between 0 and 2^63 - 1.")
    if not 1 <= batch_size <= 256:
        raise ValueError("Inference batch size must be 1-256.")
    model.eval()
    positions = [
        (index, character) for index, character in enumerate(text) if character in CHAR_TO_LABEL
    ]
    if not positions:
        return {}
    device = next(model.parameters()).device
    generator = torch.Generator(device=device).manual_seed(seed)
    latent = torch.randn(
        (len(positions), model.config.latent_dim), device=device, generator=generator
    )
    labels = torch.tensor([CHAR_TO_LABEL[c] for _, c in positions], device=device)
    masks = {}
    with tqdm(
        total=len(positions),
        desc="Generate characters",
        unit="glyph",
        ascii=True,
        dynamic_ncols=True,
        disable=not show_progress,
    ) as progress:
        for start in range(0, len(positions), batch_size):
            stop = min(start + batch_size, len(positions))
            probabilities = model.decode(latent[start:stop], labels[start:stop]).sigmoid().cpu()
            if not torch.isfinite(probabilities).all():
                raise FloatingPointError("Model produced non-finite glyphs.")
            for (index, _), image in zip(positions[start:stop], probabilities, strict=True):
                pixels = (image.squeeze(0) * 255).round().to(torch.uint8).numpy()
                masks[index] = Image.fromarray(pixels)
            progress.update(stop - start)
    return masks


def create_preview(
    text: str,
    *,
    checkpoint=DEFAULT_CHECKPOINT,
    output=Path("artifacts/paragraph-preview"),
    options=None,
    seed=42,
    device="cpu",
    apply_normalization=False,
    show_progress=True,
):
    options = options or LayoutOptions()
    rendered_text = prepare_text(text, apply_normalization)
    if output.exists():
        raise FileExistsError("Preview output already exists; choose a new directory.")
    start = time.perf_counter()
    seed_everything(seed)
    torch.set_num_threads(4)
    print("Loading trained checkpoint for inference...", flush=True)
    model, metadata = load_checkpoint(checkpoint, resolve_device(device))
    masks = sample_occurrences(model, rendered_text, seed, show_progress=show_progress)
    print("Laying out words, lines and pages...", flush=True)
    layout = layout_text(rendered_text, masks, options)
    pages = compose_pages(layout, options)
    warnings = [
        "Letters and digits come from the trained model. Punctuation is drawn procedurally.",
        "These are isolated glyphs: the renderer does not add cursive joins "
        "or correct wrong letters.",
        "Model glyphs are 28x28 before cropping/scaling; "
        "enlargement does not add learned stroke detail.",
        "Glyph proportions and baselines are renderer heuristics and may need calibration.",
        "Raw grayscale ink is retained; no sharpening, threshold cleanup "
        "or sample rejection is applied.",
    ]
    if not masks:
        warnings.append(
            "This input has no alphanumerics; "
            "its visible output is entirely procedural punctuation."
        )
    low_ink_indices = [index for index, mask in masks.items() if mask.getextrema()[1] < 77]
    if low_ink_indices:
        warnings.append(
            f"{len(low_ink_indices)} generated glyph(s) have very weak ink and may look blank."
        )
    if metadata.get("quality_status") == "pipeline-smoke-only":
        warnings.append(
            "This checkpoint is a smoke-test artifact, not an evaluated handwriting model."
        )
    manifest = {
        "renderer_version": RENDERER_VERSION,
        "checkpoint": str(checkpoint),
        "checkpoint_sha256": sha256_file(checkpoint),
        "checkpoint_epoch": metadata.get("epoch"),
        "model_quality_status": metadata.get("quality_status", "unreviewed"),
        "seed": seed,
        "device": str(next(model.parameters()).device),
        "original_text": text,
        "rendered_text": rendered_text,
        "normalization_applied": text != rendered_text,
        "layout": asdict(options),
        "page_count": len(pages),
        "pages": [],
        "warnings": warnings,
        "placements": [asdict(item) for item in layout.placements],
        "placement_index_basis": "zero-based positions in rendered_text",
        "low_ink_glyph_indices": low_ink_indices,
        "coverage": {
            "model_glyphs": len(masks),
            "procedural_punctuation": sum(item.kind == "procedural" for item in layout.placements),
            "spaces": rendered_text.count(" "),
            "newlines": rendered_text.count("\n"),
            "visible_characters": len(layout.placements),
        },
        "training_performed": False,
    }
    output.mkdir(parents=True, exist_ok=False)
    for index, page in enumerate(pages, 1):
        filename = f"page-{index:03d}.png"
        page.save(output / filename)
        manifest["pages"].append(
            {
                "index": index,
                "filename": filename,
                "width": page.width,
                "height": page.height,
                "sha256": sha256_file(output / filename),
            }
        )
    # Preserve source line endings; Windows text-mode writes would duplicate existing CRLFs.
    (output / "input.txt").write_bytes(text.encode("utf-8"))
    manifest["duration_seconds"] = time.perf_counter() - start
    write_json(output / "manifest.json", manifest)
    write_report(output, manifest)
    print(f"Preview: {(output / 'preview.html').resolve()}", flush=True)
    print(
        f"PNG pages: {len(pages)}; model glyphs: {len(masks)}; training performed: no", flush=True
    )
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    text_group = parser.add_mutually_exclusive_group()
    text_group.add_argument(
        "--text", type=str, help="Text to render; defaults to the demo passage."
    )
    text_group.add_argument("--text-file", type=Path, help="Read UTF-8 text from a file.")
    parser.add_argument("--checkpoint", type=Path, default=DEFAULT_CHECKPOINT)
    parser.add_argument("--output", type=Path, default=Path("artifacts/paragraph-preview"))
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--device", choices=["cpu", "cuda", "auto"], default="cpu")
    parser.add_argument("--width", type=int, default=1240)
    parser.add_argument("--height", type=int, default=1754)
    parser.add_argument("--margin", type=int, default=80)
    parser.add_argument("--glyph-size", type=int, default=32)
    parser.add_argument("--character-spacing", type=int, default=2)
    parser.add_argument("--word-spacing", type=int, default=0)
    parser.add_argument("--line-spacing", type=int, default=12)
    parser.add_argument("--paper", choices=["plain", "ruled", "grid"], default="ruled")
    parser.add_argument(
        "--normalize",
        action="store_true",
        help="Explicitly normalize smart punctuation/tabs/line endings.",
    )
    parser.add_argument("--no-progress", action="store_true")
    args = parser.parse_args()
    if args.text_file:
        if args.text_file.stat().st_size > 64 * 1024:
            parser.error("Input file exceeds 64 KiB.")
        text = args.text_file.read_bytes().decode("utf-8-sig")
    else:
        text = args.text if args.text is not None else DEMO_TEXT
    options = LayoutOptions(
        width=args.width,
        height=args.height,
        margin=args.margin,
        glyph_size=args.glyph_size,
        character_spacing=args.character_spacing,
        word_spacing=args.word_spacing,
        line_spacing=args.line_spacing,
        paper=args.paper,
    )
    create_preview(
        text,
        checkpoint=args.checkpoint,
        output=args.output,
        options=options,
        seed=args.seed,
        device=args.device,
        apply_normalization=args.normalize,
        show_progress=not args.no_progress,
    )


if __name__ == "__main__":
    main()
